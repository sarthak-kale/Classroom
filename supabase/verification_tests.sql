-- SQL Verification Script for ClassFlow RLS & Business Rules
-- Run this script in the Supabase SQL editor to test policies and constraints.

DO $$
DECLARE
    v_teacher_id UUID := gen_random_uuid();
    v_student1_id UUID := gen_random_uuid();
    v_student2_id UUID := gen_random_uuid();
    v_intruder_id UUID := gen_random_uuid();
    v_class_id UUID;
    v_mat_id UUID;
    v_asgn_id UUID;
    v_code TEXT;
    v_sub_res JSONB;
    v_view_res JSONB;
BEGIN
    RAISE NOTICE '=== STARTING CLASSFLOW INTEGRATION TESTS ===';

    -- 1. Test Profile Creation & Role Invariance
    INSERT INTO public.profiles (id, email, full_name, role)
    VALUES (v_teacher_id, 'teacher@test.local', 'Professor Smith', 'teacher');

    INSERT INTO public.profiles (id, email, full_name, role)
    VALUES (v_student1_id, 'student1@test.local', 'Alice Student', 'student');

    INSERT INTO public.profiles (id, email, full_name, role)
    VALUES (v_student2_id, 'student2@test.local', 'Bob Student', 'student');

    INSERT INTO public.profiles (id, email, full_name, role)
    VALUES (v_intruder_id, 'intruder@test.local', 'Eve Intruder', 'student');

    -- Verify role immutability
    BEGIN
        UPDATE public.profiles SET role = 'teacher' WHERE id = v_student1_id;
        RAISE EXCEPTION 'TEST FAILED: Role update should have been rejected by trigger';
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'SUCCESS: Role immutability trigger rejected role modification.';
    END;

    -- 2. Test Classroom Creation and Unique Join Code
    -- Test automatic default join code generation
    INSERT INTO public.classrooms (name, section, subject, teacher_id)
    VALUES ('Physics 101', 'Period 1', 'Quantum Mechanics', v_teacher_id)
    RETURNING id, join_code INTO v_class_id, v_code;

    IF v_code IS NULL OR length(v_code) = 0 THEN
        RAISE EXCEPTION 'TEST FAILED: join_code was not generated by database default';
    END IF;

    RAISE NOTICE 'SUCCESS: Created classroom with auto-generated code %', v_code;

    -- Test join_code immutability trigger
    BEGIN
        UPDATE public.classrooms SET join_code = 'CF-HACKED' WHERE id = v_class_id;
        RAISE EXCEPTION 'TEST FAILED: Classroom join code modification should be rejected by trigger';
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'SUCCESS: Prevented join code tampering via trigger.';
    END;

    -- 3. Test Student Membership (Alice and Bob join)
    INSERT INTO public.classroom_members (classroom_id, student_id)
    VALUES (v_class_id, v_student1_id);

    INSERT INTO public.classroom_members (classroom_id, student_id)
    VALUES (v_class_id, v_student2_id);

    -- Test duplicate membership rejection
    BEGIN
        INSERT INTO public.classroom_members (classroom_id, student_id)
        VALUES (v_class_id, v_student1_id);
        RAISE EXCEPTION 'TEST FAILED: Duplicate student enrollment was allowed.';
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'SUCCESS: Duplicate student enrollment prevented by unique constraint.';
    END;

    -- 4. Test Material Creation (Draft vs Published)
    INSERT INTO public.materials (classroom_id, title, description, published_at)
    VALUES (v_class_id, 'Draft Syllabus', 'Not ready yet', NULL);

    INSERT INTO public.materials (classroom_id, title, description, published_at)
    VALUES (v_class_id, 'Lecture 1: Kinematics', 'Introductory slides', now())
    RETURNING id INTO v_mat_id;

    RAISE NOTICE 'SUCCESS: Created draft and published materials.';

    -- 5. Test Assignment Creation & Marks Validation
    INSERT INTO public.assignments (classroom_id, title, instructions, max_marks, due_at, published_at)
    VALUES (v_class_id, 'Problem Set 1', 'Solve problems 1-10', 100.00, now() + interval '7 days', now())
    RETURNING id INTO v_asgn_id;

    -- Verify marks constraint trigger
    BEGIN
        INSERT INTO public.assignment_submissions (assignment_id, student_id, marks_obtained)
        VALUES (v_asgn_id, v_student1_id, 150.00);
        RAISE EXCEPTION 'TEST FAILED: Submissions marks (> max_marks) was accepted.';
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'SUCCESS: Marks validation trigger rejected marks > max_marks.';
    END;

    -- 6. Cleanup test records
    DELETE FROM public.classrooms WHERE id = v_class_id;
    DELETE FROM public.profiles WHERE id IN (v_teacher_id, v_student1_id, v_student2_id, v_intruder_id);

    RAISE NOTICE '=== ALL INTEGRATION VERIFICATION TESTS PASSED SUCCESSFULLY ===';
END $$;
